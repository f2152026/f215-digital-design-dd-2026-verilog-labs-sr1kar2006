// cla64_flat.v
// Flat (unblocked) 64-bit carry-lookahead adder.
// Every carry is computed directly from the propagate/generate
// signals via the standard CLA sum-of-products expansion:
//   c[k+1] = g[k] | p[k]&g[k-1] | p[k]&p[k-1]&g[k-2] | ... | (p[k]..p[0])&cin
// To keep it compilable at 64 bits, each carry reuses a running
// propagate-product (pp_k_*) instead of re-expanding every term.
module cla64_flat(
  input  [63:0] a,
  input  [63:0] b,
  input         cin,
  output [63:0] sum,
  output        cout
);

  wire [63:0] p, g;
  wire [64:0] c;
  assign c[0] = cin;

  // ---- Step 1: propagate & generate (uniform -> generate loop) ----
  genvar i;
  generate
    for (i = 0; i < 64; i = i + 1) begin : pg
      assign p[i] = a[i] ^ b[i];
      assign g[i] = a[i] & b[i];
    end
  endgenerate

  // ---- Step 2: direct carry equations (flat CLA, no rippling) ----
  wire pp_0_0;
  assign pp_0_0 = p[0];
  assign c[1] = g[0] | (pp_0_0 & cin);

  wire pp_1_0, pp_1_1;
  assign pp_1_1 = p[1];
  assign pp_1_0 = pp_1_1 & p[0];
  assign c[2] = g[1] | (pp_1_1 & g[0]) | (pp_1_0 & cin);

  wire pp_2_0, pp_2_1, pp_2_2;
